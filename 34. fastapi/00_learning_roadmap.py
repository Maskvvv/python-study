# ============================================
# 为什么学 FastAPI？
# ============================================
"""
1. 性能极高
   - 基于 Starlette + Pydantic，性能媲美 NodeJS / Go
   - 异步原生支持，轻松处理高并发

2. 开发效率高
   - 自动生成 OpenAPI 文档（Swagger UI + ReDoc）
   - 类型注解驱动，IDE 补全体验极佳
   - 数据验证自动完成，不用手写校验逻辑

3. 现代化设计
   - 基于Python类型注解（type hints）
   - 异步/同步都支持
   - 依赖注入系统优雅强大

4. 生态友好
   - 和 Pydantic 深度集成（你已经学过了！）
   - 兼容 ASGI 服务器（Uvicorn、Hypercorn）
   - 可以和 SQLAlchemy、Tortoise ORM 等数据库工具配合
"""

